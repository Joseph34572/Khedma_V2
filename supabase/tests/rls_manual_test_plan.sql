-- خطة اختبار يدوية لسياسات RLS (نفّذها من SQL Editor في Supabase بعد تطبيق
-- الهجرات وإدخال بيانات تجريبية: مديرًا عامًا، أمين خدمة لكل مرحلة، خادمًا لكل
-- مرحلة، وعدة أولاد موزّعين على المراحل الثلاث).
--
-- الفكرة: `set local role authenticated; set local request.jwt.claims ...`
-- لا يعمل مباشرة بنفس آلية Supabase الداخلية، لذا الطريقة العملية الموصى بها
-- هي اختبار هذه الحالات فعليًا عبر:
--   1) تسجيل الدخول بحساب خادم "أولى إعدادي" من التطبيق أو من Postman باستخدام
--      anon key + access_token الخاص بجلسته.
--   2) محاولة استعلام مباشر لبيانات ولد في "تانية إعدادي" بنفس التوكن.
--   3) التأكد أن النتيجة صف فارغ (0 rows) وليس خطأ صلاحيات صريح — لأن RLS
--      تُخفي الصفوف غير المسموح بها بدلًا من رفض الاستعلام.
--
-- الحالات الواجب اختبارها يدويًا قبل أي نشر فعلي:
--
-- [ ] 1. خادم "أولى إعدادي" يرى فقط أولاد أولى إعدادي في child_activity_summary
-- [ ] 2. خادم "أولى إعدادي" لا يرى صف أي ولد من "تانية/تالتة إعدادي" حتى بمعرفة الـ id مباشرة:
--        select * from profiles where id = '<uuid ولد من مرحلة أخرى>';  -- يجب أن يُرجع 0 صفوف
-- [ ] 3. خادم لا يستطيع إدراج صف في profiles (إنشاء مستخدم) — يجب أن يفشل الإدراج
-- [ ] 4. خادم لا يستطيع تغيير دوره الخاص أو مرحلته عبر تعديل مباشر لصفه في profiles
-- [ ] 5. مستخدم عادي (ولد) يرى فقط صفوفه في prayer_sessions / bible_reading_sessions
-- [ ] 6. مستخدم عادي لا يرى جلسات صلاة ولد آخر حتى لو عرف الـ id
-- [ ] 7. جدول confessions: الخادم لا يرى صفوف اعتراف أي ولد؛ فقط صاحب الصف والمدير/الأمين العام
-- [ ] 8. محاولة تسجيل حضور قداس مرتين لنفس المستخدم لنفس القداس تفشل (unique constraint)
-- [ ] 9. محاولة إنشاء مدير عام ثانٍ تفشل (unique index one_super_admin_only)
-- [ ] 10. audit_log: لا يوجد أي عميل عادي (حتى المدير العام من الواجهة) يستطيع الإدراج
--         مباشرة؛ الإدراج فقط عبر service role من الخادم
-- [ ] 11. أمين خدمة "تانية إعدادي" لا يرى صندوق ندوة أسئلة "تالتة إعدادي"
-- [ ] 12. سؤال صندوق ندوة مُرسل كمجهول: التأكد أن واجهات الخادم لا تعرض اسم صاحب
--         السؤال في أي مكان لا يحتاج معرفة الهوية (يُراجع عند بناء واجهات المرحلة الرابعة)
--
-- يُنصح بأتمتة الحالات أعلاه لاحقًا باستخدام pgTAP داخل Supabase CLI:
--   supabase test db
-- أو عبر اختبارات تكامل بـ Playwright تُسجّل دخول بحسابات حقيقية وتتحقق من
-- الاستجابات، بدل الاعتماد على مراجعة يدوية فقط قبل كل نشر.

